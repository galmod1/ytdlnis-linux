def t(key, **kw):
    text = TRANSLATIONS.get(_LANG, {}).get(key)
    if text is None:
        text = TRANSLATIONS["ar"].get(key, key)
    if kw:
        try:
            return text.format(**kw)
        except Exception:
            return text
    return text
